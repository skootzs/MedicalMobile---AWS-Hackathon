export const TASKS_FILE = 'tasks.js';
export const TRANSLATIONS_FILE = 'translations/messages-en.properties';

export interface TaskWindow {
  /** Days before the due date that the task appears. */
  start: number;
  /** Days after the due date that the task stays open. */
  end: number;
}

export const DEFAULT_TASK_WINDOW: TaskWindow = { start: 0, end: 2 };

export interface GeneratedTasks {
  tasksJs: string;
  translations: Record<string, string>;
  summary: { name: string; title: string; window: TaskWindow; windowSource: 'option' | 'default'; outcomes: string[] };
}

function escapeProperty(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/^ /, '\\ ');
}

export function translationsFile(translations: Record<string, string>): string {
  return Object.keys(translations)
    .sort()
    .map((k) => `${k} = ${escapeProperty(translations[k]!)}\n`)
    .join('');
}

// One follow-up task per pathway: raised by any report of the form whose t_follow_up_date is set,
// due on that date, and resolved by a later report of the same form for the same contact inside the window.
export function buildTasks(input: {
  formId: string;
  title: string;
  icon: string;
  inputHash: string;
  followUpOutcomes: string[];
  window: TaskWindow;
  windowSource: 'option' | 'default';
}): GeneratedTasks | null {
  if (input.followUpOutcomes.length === 0) return null;
  const { formId, icon, window } = input;
  const name = `${formId}_follow_up`;
  const titleKey = `task.${formId}.follow_up.title`;
  const title = `Follow up: ${input.title}`;
  // cht-conf lints tasks.js with its own rules, which require single quotes.
  const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

  const tasksJs = `// Generated by @cht-nocode/compiler from LogicModel ${input.inputHash}.
// Do not edit by hand: change the approved LogicModel and recompile.
// Raised for outcomes: ${input.followUpOutcomes.join(', ')}.
const FORM = ${q(formId)};

function followUpDate(report) {
  const value = Utils.getField(report, 't_follow_up_date');
  if (!value) return null;
  const date = new Date(value);
  return isNaN(date.getTime()) ? null : date;
}

module.exports = [
  {
    name: ${q(name)},
    icon: ${q(icon)},
    title: ${q(titleKey)},
    appliesTo: 'reports',
    appliesToType: [FORM],
    appliesIf: function (contact, report) {
      return followUpDate(report) !== null;
    },
    actions: [{ type: 'report', form: FORM }],
    events: [
      {
        id: ${q(name)},
        start: ${window.start},
        end: ${window.end},
        dueDate: function (event, contact, report) {
          return followUpDate(report);
        },
      },
    ],
    resolvedIf: function (contact, report, event, dueDate) {
      const from = Utils.addDate(dueDate, -event.start).getTime();
      const to = Utils.addDate(dueDate, event.end + 1).getTime();
      return contact.reports.some(function (r) {
        return r.form === FORM && r._id !== report._id && r.reported_date > report.reported_date &&
          r.reported_date >= from && r.reported_date < to;
      });
    },
  },
];
`;
  return {
    tasksJs,
    translations: { [titleKey]: title },
    summary: { name, title, window, windowSource: input.windowSource, outcomes: input.followUpOutcomes },
  };
}
